"""BC-5 golden: the pre-refactor template and token-table facts at base 93b659c.

The fixture ``tests/fixtures/decision/golden_record_refactor_93b659c.json`` was
generated by the base code with the exact procedure below.  These tests re-run
that procedure against the code under test and assert that every field of the
fixture is reproduced byte-for-byte, so the record refactor (chunks 03-05) can
be proven not to change a single byte of what the template and token table
produce (gate condition BC-5 / AC-MA5).
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from audittrace.services.decision import template as tpl
from audittrace.services.decision.questions import QUESTIONS
from audittrace.services.decision.token_tables import table_for
from tests.fakes.decision_server import fake_tokenize

FIXTURE_PATH = (
    Path(__file__).parent
    / "fixtures"
    / "decision"
    / "golden_record_refactor_93b659c.json"
)

QUESTION_KEY = "memory_layer_v1"
TABLE_DIGEST = "4f8a3d7fc2c8eda2601751ace44690ba1080e508842df88644cedcc08af82cdf"
EXPECTED_BASE = "93b659c3294dec962618373a3cc3a472e643aea7"
EXPECTED_TRIPLE_COUNT = 33


def _golden() -> dict[str, Any]:
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def _case_fields(state: str) -> tuple[str, str, list[int], str]:
    """Re-run the generation procedure for one state (same as the brief)."""
    question = QUESTIONS[QUESTION_KEY]
    special = {t: fake_tokenize(t, True)[0] for t in tpl.TEMPLATE_SPECIAL_TOKENS}
    pieces = {t: fake_tokenize(t, False) for t in tpl.TEMPLATE_TEXT_PIECES}
    content = tpl.build_user_content(state, question.text, question.options)
    rendered = tpl.render_choice_prompt(state, question.text, question.options)
    ids = tpl.splice_prompt_ids(special, pieces, fake_tokenize(content, False))
    return (
        hashlib.sha256(content.encode()).hexdigest(),
        tpl.rendered_sha256(rendered),
        ids,
        tpl.input_sha256(ids),
    )


def _cases(golden: dict[str, Any]) -> list[Any]:
    return list(golden["cases"])


def test_golden_template_identity() -> None:
    golden = _golden()
    assert golden["template_id"] == tpl.TEMPLATE_ID
    assert golden["template_sha256"] == tpl.TEMPLATE_SHA256
    assert golden["template_source"] == tpl.TEMPLATE_SOURCE
    assert golden["upstream_chat_template_sha256"] == tpl.UPSTREAM_CHAT_TEMPLATE_SHA256


def test_golden_special_tokens_and_text_pieces() -> None:
    golden = _golden()
    assert golden["special_tokens"] == list(tpl.TEMPLATE_SPECIAL_TOKENS)
    assert golden["text_pieces"] == list(tpl.TEMPLATE_TEXT_PIECES)


def test_golden_content_literals_and_letters() -> None:
    golden = _golden()
    assert golden["content_literals"] == [
        tpl.STATE_HEAD,
        tpl.QUESTION_HEAD,
        tpl.OPTIONS_HEAD,
        tpl.OPTION_SEP,
        tpl.INSTRUCTION,
    ]
    assert golden["letters"] == tpl.LETTERS


def test_golden_table_identity() -> None:
    golden = _golden()
    table = table_for(TABLE_DIGEST)
    assert table is not None
    assert golden["table"]["digest"] == TABLE_DIGEST
    assert golden["table"]["source"] == table.source
    assert golden["table"]["tokenizer_config_sha256"] == table.tokenizer_config_sha256


def test_golden_table_triples() -> None:
    golden = _golden()
    table = table_for(TABLE_DIGEST)
    assert table is not None
    triples = [[i, t.content, t.special] for i, t in table.tokens.items()]
    assert len(triples) == EXPECTED_TRIPLE_COUNT
    assert golden["table"]["tokens"] == triples


def test_golden_cases_content_sha256() -> None:
    golden = _golden()
    for case in _cases(golden):
        (content_sha, _, _, _) = _case_fields(str(case["state"]))
        assert case["content_sha256"] == content_sha


def test_golden_cases_rendered_sha256() -> None:
    golden = _golden()
    for case in _cases(golden):
        (_, rendered_sha, _, _) = _case_fields(str(case["state"]))
        assert case["rendered_sha256"] == rendered_sha


def test_golden_cases_prompt_ids() -> None:
    golden = _golden()
    for case in _cases(golden):
        (_, _, ids, _) = _case_fields(str(case["state"]))
        assert case["prompt_ids"] == ids


def test_golden_cases_input_sha256() -> None:
    golden = _golden()
    for case in _cases(golden):
        (_, _, _, input_sha) = _case_fields(str(case["state"]))
        assert case["input_sha256"] == input_sha


def test_golden_base() -> None:
    assert _golden()["base"] == EXPECTED_BASE
