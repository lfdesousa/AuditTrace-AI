def _write(tmp_path: Path, lock: str = LOCK) -> tuple[Path, Path]:
    lockfile = tmp_path / "requirements-dev.txt"
    lockfile.write_text(lock)
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text(PYPROJECT_TEXT)
    return lockfile, pyproject


def test_main_returns_zero_when_the_environment_is_the_lock(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    lockfile, pyproject = _write(tmp_path)
    monkeypatch.setattr(cvl, "installed_distributions", good_env)
    rc = cvl.main([str(lockfile), "--pyproject", str(pyproject)])
    out = capsys.readouterr()
    assert rc == 0 and "environment ==" in out.out


def test_main_fails_closed_and_prints_the_recovery_path(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    lockfile, pyproject = _write(tmp_path)
    env = good_env()
    env["fastapi"] = FakeDist("0.141.1")
    monkeypatch.setattr(cvl, "installed_distributions", lambda: env)
    rc = cvl.main([str(lockfile), "--pyproject", str(pyproject)])
    err = capsys.readouterr().err
    assert rc == 1
    assert "fastapi" in err and "rm -rf .venv && make venv" in err


def test_main_truncates_a_long_problem_list(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    lockfile, pyproject = _write(tmp_path)
    env = good_env()
    for i in range(60):
        env[f"extra-{i}"] = FakeDist("1")
    monkeypatch.setattr(cvl, "installed_distributions", lambda: env)
    assert cvl.main([str(lockfile), "--pyproject", str(pyproject)]) == 1
    assert "... and 20 more" in capsys.readouterr().err


def test_there_is_no_flag_or_env_bypass(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The CLI surface is exactly: the lock path (+ a hidden --pyproject for
    tests). Nothing that skips, warns or downgrades; no environment read."""
    import argparse

    seen: list[str] = []
    original = argparse.ArgumentParser.add_argument

    def spy(self: argparse.ArgumentParser, *a: Any, **kw: Any) -> Any:
        seen.append(a[0])
        return original(self, *a, **kw)

    monkeypatch.setattr(argparse.ArgumentParser, "add_argument", spy)
    with pytest.raises(SystemExit):
        cvl.main(["--help"])
    assert {"lock", "--pyproject"} <= set(seen) <= {"lock", "--pyproject", "-h"}
    source = (ROOT / "scripts/ci/check_venv_matches_lock.py").read_text()
    assert "os.environ" not in source and "getenv" not in source
