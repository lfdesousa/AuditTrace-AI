"""G5 — ``scripts/ci/check_venv_matches_lock.py`` (DEP-LOCK-AT C2).

The checker refuses a test run on an interpreter whose environment is not the
hashed lock. Each check has a case here that goes RED when its branch is
removed (N8: `pip install fastapi==0.141.1` into the venv -> refused).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest

from scripts.ci import check_venv_matches_lock as cvl

ROOT = Path(__file__).resolve().parent.parent
SHA = "cc21c5530e1a471d48b697f3ff8f3df1cd5c0185"
PYPROJECT_TEXT = (
    '[project]\nname = "audittrace-ai"\nversion = "1.2.3"\ndependencies = [\n'
    f'  "audittrace-object-storage @ git+https://github.com/o/audittrace-object-storage.git@{SHA}",\n]\n'
)
LOCK = """\
# This file was autogenerated by uv via the following command:
#    uv pip compile pyproject.toml --universal --generate-hashes --python-version 3.12 -o requirements-dev.txt
fastapi==0.146.0 \\
    --hash=sha256:aa
    # via audittrace-ai
colorama==0.4.6 ; sys_platform == 'win32' \\
    --hash=sha256:bb
pip==26.2.1 \\
    --hash=sha256:cc
Weird_Name==1.0 \\
    --hash=sha256:dd
"""


class FakeDist:
    """The slice of ``importlib.metadata.Distribution`` the checker reads."""

    def __init__(
        self,
        version: str,
        direct_url: dict[str, Any] | str | None = None,
    ) -> None:
        self.version = version
        self._direct_url = direct_url

    def read_text(self, filename: str) -> str | None:
        assert filename == "direct_url.json"
        if self._direct_url is None:
            return None
        if isinstance(self._direct_url, str):
            return self._direct_url
        return json.dumps(self._direct_url)


def good_env() -> dict[str, Any]:
    return {
        "fastapi": FakeDist("0.146.0"),
        "pip": FakeDist("26.2.1"),
        "weird-name": FakeDist("1.0"),
        "audittrace-ai": FakeDist("1.2.3", {"dir_info": {"editable": True}}),
        "audittrace-object-storage": FakeDist(
            "0.1.1", {"vcs_info": {"commit_id": SHA}}
        ),
    }


def run(
    env: dict[str, Any] | None = None,
    lock: str = LOCK,
    pyproject_text: str = PYPROJECT_TEXT,
    py: tuple[int, int] = (3, 12),
) -> list[str]:
    import tomllib

    return cvl.check(
        lock,
        tomllib.loads(pyproject_text),
        pyproject_text,
        good_env() if env is None else env,
        py,
    )


def test_a_matching_environment_has_no_violations() -> None:
    assert run() == []


def test_a_wrong_version_is_flagged_n8() -> None:
    env = good_env()
    env["fastapi"] = FakeDist("0.141.1")
    assert any("fastapi: installed 0.141.1, lock pins 0.146.0" in p for p in run(env))


def test_a_missing_pin_is_flagged() -> None:
    env = good_env()
    del env["fastapi"]
    assert any(
        "fastapi==0.146.0 is in the lock but NOT installed" in p for p in run(env)
    )


def test_an_extra_package_is_flagged_but_the_two_known_extras_are_allowed() -> None:
    env = good_env()
    env["requests"] = FakeDist("2.0")
    problems = run(env)
    assert any("requests==2.0 is installed but NOT in the lock" in p for p in problems)
    assert not any("audittrace" in p for p in problems)


def test_a_marker_that_does_not_apply_is_not_required() -> None:
    env = good_env()  # colorama (win32-only) is not installed
    assert not any("colorama" in p for p in run(env))


def test_a_marker_that_applies_is_required(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(cvl, "marker_applies", lambda marker: True)
    assert any("colorama==0.4.6 is in the lock but NOT installed" in p for p in run())


def test_an_unparseable_marker_fails_closed() -> None:
    assert cvl.marker_applies("this is !! not a marker") is True
    assert cvl.marker_applies(None) is True
    assert cvl.marker_applies("sys_platform == 'win32'") is False


def test_canonical_name_matching_covers_underscores_and_case() -> None:
    env = good_env()
    del env["weird-name"]
    assert any(
        "weird-name==1.0 is in the lock but NOT installed" in p for p in run(env)
    )


def test_the_project_must_be_installed() -> None:
    env = good_env()
    del env["audittrace-ai"]
    assert any("audittrace-ai is not installed" in p for p in run(env))


def test_the_project_version_must_match_pyproject() -> None:
    env = good_env()
    env["audittrace-ai"] = FakeDist("9.9.9", {"dir_info": {"editable": True}})
    assert any("installed 9.9.9, pyproject says 1.2.3" in p for p in run(env))


@pytest.mark.parametrize("direct_url", [None, {"dir_info": {}}, "{not json"])
def test_the_project_must_be_an_editable_install(direct_url: Any) -> None:
    env = good_env()
    env["audittrace-ai"] = FakeDist("1.2.3", direct_url)
    assert any("not an editable install" in p for p in run(env))


def test_the_vcs_package_commit_must_equal_the_pyproject_sha() -> None:
    env = good_env()
    env["audittrace-object-storage"] = FakeDist(
        "0.1.1", {"vcs_info": {"commit_id": "0" * 40}}
    )
    assert any("installed commit" in p and SHA in p for p in run(env))


@pytest.mark.parametrize("direct_url", [None, "{not json", {"vcs_info": {}}])
def test_a_vcs_package_without_a_readable_commit_is_flagged(direct_url: Any) -> None:
    env = good_env()
    env["audittrace-object-storage"] = FakeDist("0.1.1", direct_url)
    assert any("installed commit None" in p for p in run(env))


def test_the_vcs_package_must_be_installed() -> None:
    env = good_env()
    del env["audittrace-object-storage"]
    assert any("audittrace-object-storage is not installed" in p for p in run(env))


def test_pyproject_without_a_vcs_sha_is_flagged() -> None:
    text = PYPROJECT_TEXT.replace(SHA, "v0.1.1")
    assert any("no 40-hex" in p for p in run(pyproject_text=text))


def test_interpreter_must_match_the_lock_header() -> None:
    assert any("interpreter is 3.13" in p for p in run(py=(3, 13)))


def test_a_lock_without_a_python_version_header_is_flagged() -> None:
    lock = "\n".join(line for line in LOCK.splitlines() if "uv pip compile" not in line)
    assert any("no --python-version" in p for p in run(lock=lock))


def test_parse_lock_reads_markers_and_header() -> None:
    pins, header = cvl.parse_lock(LOCK)
    assert header == "3.12"
    assert pins["fastapi"] == ("0.146.0", None)
    assert pins["colorama"] == ("0.4.6", "sys_platform == 'win32'")
    assert pins["weird-name"][0] == "1.0"


def test_installed_distributions_reads_the_real_environment() -> None:
    dists = cvl.installed_distributions()
    assert "pytest" in dists and dists["pytest"].version


